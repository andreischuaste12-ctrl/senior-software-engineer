"""Automated evaluation harness for the skill scenarios.

Each scenario creates a disposable fixture, runs the agent with a real model, and
applies deterministic criteria to the final file state and tool calls. Run:
python -m sse_agent.evals list | run [ID ...]. A "passed" result applies only to
the model, skill revision, and fixture that were used.
"""

from collections.abc import Callable
from dataclasses import dataclass, field
import hashlib
import json
import os
from pathlib import Path
import posixpath
import re
import subprocess
import sys
import tempfile
from typing import Any

from .agent import DEFAULT_BASE_URL, AgentError, Client, run
from .arguments import positive, positive_float
from .paths import matches_pattern
from .tools import Workspace, check_environment

Snapshot = dict[str, str]
Calls = list[tuple[str, dict[str, Any]]]


class CallLog(list[tuple[str, dict[str, Any]]]):
    """All attempts plus the subset that completed without a tool error."""

    def __init__(self) -> None:
        super().__init__()
        self.successful: Calls = []


class RecordingWorkspace(Workspace):
    """Workspace that records every tool call for evaluation criteria."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self.calls = CallLog()

    def execute(self, name: str, arguments: Any) -> dict[str, Any]:
        recorded = arguments if isinstance(arguments, dict) else {}
        result = super().execute(name, arguments)
        self.calls.append((name, recorded))
        if 'error' not in result:
            self.calls.successful.append((name, recorded))
        return result


@dataclass
class Scenario:
    id: str
    title: str
    task: str
    files: dict[str, str]
    grade: Callable[[Path, Snapshot, str, Calls], list[str]]
    allow_write: bool = False
    checks: dict[str, list[str]] = field(default_factory=dict)


def snapshot(root: Path) -> Snapshot:
    # Caches generated by checks themselves (bytecode) are not agent changes.
    return {path.relative_to(root).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted(root.rglob('*'))
            if path.is_file() and '__pycache__' not in path.relative_to(root).parts}


def unittest_passes(root: Path) -> bool:
    try:
        result = subprocess.run([sys.executable, '-m', 'unittest', 'discover', '-s', '.'], cwd=root,
                                env=check_environment(), capture_output=True, timeout=60, check=False)
        return result.returncode == 0
    except subprocess.TimeoutExpired:
        return False


def unittest_target_passes(root: Path, target: str) -> bool:
    try:
        result = subprocess.run([sys.executable, '-m', 'unittest', target], cwd=root,
                                env=check_environment(), capture_output=True, timeout=60, check=False)
        return result.returncode == 0
    except subprocess.TimeoutExpired:
        return False


def changed(before: Snapshot, after: Snapshot) -> set[str]:
    return {path for path in before.keys() | after.keys() if before.get(path) != after.get(path)}


def check_ran_after_edits(calls: Calls, check: str = 'tests') -> bool:
    effective = calls.successful if isinstance(calls, CallLog) else calls
    last_edit = max((index for index, (name, _) in enumerate(effective)
                     if name in {'write_file', 'replace_in_file'}), default=-1)
    last_check = max((index for index, (name, arguments) in enumerate(effective)
                      if name == 'run_check' and arguments.get('name') == check), default=-1)
    return last_check > last_edit


def targets_environment_file(value: Any) -> bool:
    candidate = str(value)
    if not candidate:
        return False
    parts = [part for part in candidate.replace('\\', '/').split('/') if part and part != '.']
    return (any('.env' in part.casefold() for part in parts) or
            any(matches_pattern(path, candidate) for path in ('.env', '.env.local', 'nested/.env')))


def normalized_call_path(value: Any) -> str:
    normalized = posixpath.normpath(str(value).replace('\\', '/'))
    return normalized.removeprefix('./')


